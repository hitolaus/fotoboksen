// Build-time support for running offline from the Home Screen: after the build
// is written, emit dist/sw.js, a service worker that stores every built file
// on the iPad and answers from that copy, so the app starts without network.
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, relative, sep } from 'node:path';
import type { Plugin } from 'vite';

export const SW_FILE = 'sw.js';

export interface BuiltFile {
  /** Path relative to the output directory, with forward slashes. */
  path: string;
  bytes: Uint8Array;
}

/**
 * The service worker source for a build. The cache name carries a hash of
 * every file's contents, so any change to the build installs a fresh copy
 * and removes the old one.
 */
export function serviceWorkerFor(files: BuiltFile[]): string {
  const sorted = [...files].sort((a, b) => a.path.localeCompare(b.path));
  const hash = createHash('sha256');
  for (const f of sorted) hash.update(f.path).update('\0').update(f.bytes).update('\0');
  const version = hash.digest('hex').slice(0, 12);
  // index.html is cached as "/": that is the URL the app is opened at, and
  // Cloudflare Pages redirects /index.html to /, which iOS refuses to serve
  // from a service worker for a page load.
  const urls = sorted.map((f) => (f.path === 'index.html' ? '/' : `/${f.path}`));

  return `// Generated by offline.ts. Do not edit.
const PREFIX = 'fotoboksen-';
const CACHE = PREFIX + ${JSON.stringify(version)};
const FILES = ${JSON.stringify(urls)};

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE).then((cache) =>
      cache.addAll(FILES.map((f) => new Request(new URL(f, self.location.href), { cache: 'reload' }))),
    ),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys().then((keys) =>
      Promise.all(keys.filter((k) => k.startsWith(PREFIX) && k !== CACHE).map((k) => caches.delete(k))),
    ),
  );
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return;
  const key = req.mode === 'navigate' ? '/' : url.pathname;
  event.respondWith(
    caches.open(CACHE).then((cache) => cache.match(key)).then((hit) => hit || fetch(req)),
  );
});
`;
}

function listFiles(dir: string): BuiltFile[] {
  return readdirSync(dir, { recursive: true, withFileTypes: true })
    .filter((d) => d.isFile())
    .map((d) => {
      const full = join(d.parentPath, d.name);
      return { path: relative(dir, full).split(sep).join('/'), bytes: readFileSync(full) };
    })
    .filter((f) => f.path !== SW_FILE);
}

export function offline(): Plugin {
  return {
    name: 'fotoboksen-offline',
    apply: 'build',
    writeBundle(options) {
      const dir = options.dir!;
      writeFileSync(join(dir, SW_FILE), serviceWorkerFor(listFiles(dir)));
    },
  };
}
